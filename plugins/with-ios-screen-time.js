/**
 * Expo config plugin: adds the Family Controls entitlement, an App Group, and a DeviceActivityMonitor extension for iOS Screen Time.
 * Family Controls has a single entitlement key for every build type; whether a build may carry it is decided by the provisioning profile, so dev builds sign today and TestFlight / App Store builds need Apple's distribution grant on both App IDs first.
 */
const {
  withDangerousMod,
  withEntitlementsPlist,
  withInfoPlist,
  withXcodeProject,
} = require('@expo/config-plugins');
const fs = require('fs');
const path = require('path');

const TARGET_NAME = 'MoodSenseDeviceActivityMonitor';

/**
 * Both keys are mirrored in modules/moodsense-ios-usage/ios/SharedStore.swift (infoPlistKey, Key.thresholdEvents).
 * A mismatch is silent: the app would drain an always-empty queue.
 */
const APP_GROUP_INFO_KEY = 'MoodSenseAppGroup';

const EVENTS_KEY = 'moodsense.thresholdEvents';

const DEFAULT_DEPLOYMENT_TARGET = '16.4';

function extensionSource() {
  return `import DeviceActivity
import Foundation

/**
 * Records DeviceActivity threshold crossings for the app to collect later.
 *
 * This runs in its own short-lived process. It cannot call into MoodSense and
 * MoodSense cannot call into it — the App Group container below is the only
 * channel between them.
 *
 * Generated by plugins/with-ios-screen-time.js. Edit it there, not here:
 * everything under ios/ is regenerated by \`expo prebuild\`.
 */
class ${TARGET_NAME}: DeviceActivityMonitor {
  private static let appGroupInfoKey = "${APP_GROUP_INFO_KEY}"
  private static let eventsKey = "${EVENTS_KEY}"

  /**
   * Bounded, because a participant who does not open the app for weeks keeps
   * crossing thresholds daily and this process has no time to do anything
   * clever about it. The cap is far above a plausible day's crossings.
   */
  private static let maxStoredEvents = 500

  override func eventDidReachThreshold(
    _ event: DeviceActivityEvent.Name,
    activity: DeviceActivityName
  ) {
    super.eventDidReachThreshold(event, activity: activity)

    guard
      let groupId = Bundle.main.object(forInfoDictionaryKey: Self.appGroupInfoKey) as? String,
      let defaults = UserDefaults(suiteName: groupId)
    else {
      return
    }

    var events = defaults.array(forKey: Self.eventsKey) as? [[String: Any]] ?? []
    events.append([
      "name": event.rawValue,
      "ts": Date().timeIntervalSince1970 * 1000
    ])
    if events.count > Self.maxStoredEvents {
      events.removeFirst(events.count - Self.maxStoredEvents)
    }
    defaults.set(events, forKey: Self.eventsKey)
  }
}
`;
}

function infoPlistSource() {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>CFBundleDevelopmentRegion</key>
	<string>$(DEVELOPMENT_LANGUAGE)</string>
	<key>CFBundleDisplayName</key>
	<string>${TARGET_NAME}</string>
	<key>CFBundleExecutable</key>
	<string>$(EXECUTABLE_NAME)</string>
	<key>CFBundleIdentifier</key>
	<string>$(PRODUCT_BUNDLE_IDENTIFIER)</string>
	<key>CFBundleInfoDictionaryVersion</key>
	<string>6.0</string>
	<key>CFBundleName</key>
	<string>$(PRODUCT_NAME)</string>
	<key>CFBundlePackageType</key>
	<string>$(PRODUCT_BUNDLE_PACKAGE_TYPE)</string>
	<key>CFBundleShortVersionString</key>
	<string>$(MARKETING_VERSION)</string>
	<key>CFBundleVersion</key>
	<string>$(CURRENT_PROJECT_VERSION)</string>
	<key>NSExtension</key>
	<dict>
		<key>NSExtensionPointIdentifier</key>
		<string>com.apple.deviceactivity.monitor-extension</string>
		<key>NSExtensionPrincipalClass</key>
		<string>$(PRODUCT_MODULE_NAME).${TARGET_NAME}</string>
	</dict>
	<key>${APP_GROUP_INFO_KEY}</key>
	<string>__APP_GROUP__</string>
</dict>
</plist>
`;
}

const FAMILY_CONTROLS_KEY = 'com.apple.developer.family-controls';

// Not a real entitlement — earlier versions of this plugin wrote it, and prebuild without --clean merges into the old file, so it has to be removed explicitly or signing keeps failing.
const BOGUS_DEVELOPMENT_KEY = 'com.apple.developer.family-controls.development';

function entitlementsSource(appGroup, key) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
	<key>${key}</key>
	<true/>
	<key>com.apple.security.application-groups</key>
	<array>
		<string>${appGroup}</string>
	</array>
</dict>
</plist>
`;
}

function resolveAppGroup(config, props) {
  if (props.appGroup) return props.appGroup;
  const bundleId = config.ios && config.ios.bundleIdentifier;
  if (!bundleId) {
    throw new Error(
      'with-ios-screen-time: ios.bundleIdentifier is not set, so the App Group id cannot be derived. ' +
        'Set ios.bundleIdentifier in app.json, or pass an explicit `appGroup` to this plugin.'
    );
  }
  return `group.${bundleId}.screentime`;
}

/**
 * Tells EAS the extension exists before prebuild has generated it.
 *
 * Without this, EAS resolves credentials from `ios.bundleIdentifier` alone, provisions only the app,
 * and the build dies at `Signing for "<target>" requires a development team` — the extension target is
 * conjured up during prebuild, by which point credentials are already settled. The entitlements have to
 * match `entitlementsSource()` below, since EAS uses them to decide which capabilities the extension's
 * App ID needs.
 */
function declareAppExtension(config, appGroup) {
  const extension = {
    targetName: TARGET_NAME,
    bundleIdentifier: `${config.ios.bundleIdentifier}.${TARGET_NAME}`,
    entitlements: {
      [FAMILY_CONTROLS_KEY]: true,
      'com.apple.security.application-groups': [appGroup],
    },
  };

  config.extra = config.extra || {};
  config.extra.eas = config.extra.eas || {};
  config.extra.eas.build = config.extra.eas.build || {};
  config.extra.eas.build.experimental = config.extra.eas.build.experimental || {};
  const ios = (config.extra.eas.build.experimental.ios =
    config.extra.eas.build.experimental.ios || {});

  // Replace rather than append: prebuild can re-run plugins over a config that already carries the entry.
  ios.appExtensions = [
    ...(ios.appExtensions || []).filter((e) => e.targetName !== TARGET_NAME),
    extension,
  ];

  return config;
}

module.exports = function withIosScreenTime(config, props = {}) {
  if (props.enabled === false) return config;

  const appGroup = resolveAppGroup(config, props);
  const deploymentTarget = props.deploymentTarget || DEFAULT_DEPLOYMENT_TARGET;

  config = declareAppExtension(config, appGroup);

  config = withEntitlementsPlist(config, (config) => {
    delete config.modResults[BOGUS_DEVELOPMENT_KEY];
    config.modResults[FAMILY_CONTROLS_KEY] = true;
    const groups = config.modResults['com.apple.security.application-groups'] || [];
    if (!groups.includes(appGroup)) groups.push(appGroup);
    config.modResults['com.apple.security.application-groups'] = groups;
    return config;
  });

  config = withInfoPlist(config, (config) => {
    config.modResults[APP_GROUP_INFO_KEY] = appGroup;
    return config;
  });

  config = withDangerousMod(config, [
    'ios',
    (config) => {
      const dir = path.join(config.modRequest.platformProjectRoot, TARGET_NAME);
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, `${TARGET_NAME}.swift`), extensionSource());
      fs.writeFileSync(
        path.join(dir, `${TARGET_NAME}-Info.plist`),
        infoPlistSource().replace('__APP_GROUP__', appGroup)
      );
      fs.writeFileSync(
        path.join(dir, `${TARGET_NAME}.entitlements`),
        entitlementsSource(appGroup, FAMILY_CONTROLS_KEY)
      );
      return config;
    },
  ]);

  config = withXcodeProject(config, (config) => {
    const proj = config.modResults;

    // Prebuild without --clean re-runs plugins on a project that may already have the target, and adding it twice leaves a project Xcode cannot open.
    if (proj.pbxTargetByName(TARGET_NAME)) return config;

    const files = [
      `${TARGET_NAME}.swift`,
      `${TARGET_NAME}-Info.plist`,
      `${TARGET_NAME}.entitlements`,
    ];

    const group = proj.addPbxGroup(files, TARGET_NAME, TARGET_NAME);
    const groups = proj.hash.project.objects['PBXGroup'];
    for (const key of Object.keys(groups)) {
      const entry = groups[key];
      if (typeof entry === 'object' && entry.name === undefined && entry.path === undefined) {
        proj.addToPbxGroup(group.uuid, key);
      }
    }

    // The `xcode` package crashes when adding a target dependency if these sections do not exist yet.
    const objects = proj.hash.project.objects;
    objects.PBXTargetDependency = objects.PBXTargetDependency || {};
    objects.PBXContainerItemProxy = objects.PBXContainerItemProxy || {};

    const target = proj.addTarget(
      TARGET_NAME,
      'app_extension',
      TARGET_NAME,
      `${config.ios.bundleIdentifier}.${TARGET_NAME}`
    );

    proj.addBuildPhase(
      [`${TARGET_NAME}.swift`],
      'PBXSourcesBuildPhase',
      'Sources',
      target.uuid
    );
    proj.addBuildPhase([], 'PBXResourcesBuildPhase', 'Resources', target.uuid);
    proj.addBuildPhase([], 'PBXFrameworksBuildPhase', 'Frameworks', target.uuid);

    const configurations = proj.pbxXCBuildConfigurationSection();
    for (const key of Object.keys(configurations)) {
      const buildSettings = configurations[key].buildSettings;
      if (!buildSettings || buildSettings.PRODUCT_NAME !== `"${TARGET_NAME}"`) continue;

      buildSettings.CODE_SIGN_ENTITLEMENTS = `${TARGET_NAME}/${TARGET_NAME}.entitlements`;
      buildSettings.INFOPLIST_FILE = `${TARGET_NAME}/${TARGET_NAME}-Info.plist`;
      buildSettings.GENERATE_INFOPLIST_FILE = 'NO';
      buildSettings.IPHONEOS_DEPLOYMENT_TARGET = deploymentTarget;
      buildSettings.TARGETED_DEVICE_FAMILY = '"1,2"';
      buildSettings.SWIFT_VERSION = '5.0';
      buildSettings.SWIFT_EMIT_LOC_STRINGS = 'YES';
      buildSettings.CURRENT_PROJECT_VERSION = '1';
      buildSettings.MARKETING_VERSION = config.version || '1.0.0';
      buildSettings.CLANG_ENABLE_MODULES = 'YES';
    }

    proj.addTargetDependency(proj.getFirstTarget().uuid, [target.uuid]);

    return config;
  });

  return config;
};
